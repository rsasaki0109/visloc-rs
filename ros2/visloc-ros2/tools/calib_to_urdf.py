#!/usr/bin/env python3
"""Write a URDF of a Basalt camera/IMU rig, for robot_state_publisher.

The links are `base_link`, the IMU (`imu0` by default) and one camera link per
calibrated camera (`cam0`, `cam1`, ...), each the camera's optical frame (z
forward, x right, y down) as Basalt calibrates it. The camera joints are the
calibration's `T_imu_cam`; `base_link -> imu` is `--base-from-imu` (identity
by default: on a robot, take it from the robot's own description). Name the
image topics' `frame_id`s like the camera links, or set
`visloc_map_localize_node`'s `camera_frame`.

usage: calib_to_urdf.py <calib.json> [--robot NAME] [--imu-frame imu0]
       [--camera-frame cam{}] [--base-from-imu x y z roll pitch yaw] > rig.urdf
"""

import argparse
import json
import math


def rpy_from_quaternion(x, y, z, w):
    """URDF roll/pitch/yaw (fixed-axis x, y, z) of a unit quaternion."""
    roll = math.atan2(2 * (w * x + y * z), 1 - 2 * (x * x + y * y))
    pitch = math.asin(max(-1.0, min(1.0, 2 * (w * y - z * x))))
    yaw = math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))
    return roll, pitch, yaw


def joint(name, parent, child, xyz, rpy):
    return (
        f'  <joint name="{name}" type="fixed">\n'
        f'    <parent link="{parent}"/>\n'
        f'    <child link="{child}"/>\n'
        f'    <origin xyz="{" ".join(f"{v:.9g}" for v in xyz)}" '
        f'rpy="{" ".join(f"{v:.9g}" for v in rpy)}"/>\n'
        f"  </joint>\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("calibration")
    parser.add_argument("--robot", default="visloc_rig")
    parser.add_argument("--imu-frame", default="imu0")
    parser.add_argument("--camera-frame", default="cam{}", help="camera link name, {} = index")
    parser.add_argument("--base-from-imu", type=float, nargs=6, default=[0.0] * 6,
                        metavar=("X", "Y", "Z", "ROLL", "PITCH", "YAW"))
    args = parser.parse_args()

    with open(args.calibration) as handle:
        calibration = json.load(handle)
    calibration = calibration.get("value0", calibration)
    cameras = [args.camera_frame.format(index) for index in range(len(calibration["T_imu_cam"]))]

    urdf = f'<?xml version="1.0"?>\n<!-- Generated by calib_to_urdf.py from {args.calibration} -->\n'
    urdf += f'<robot name="{args.robot}">\n'
    for link in ["base_link", args.imu_frame, *cameras]:
        urdf += f'  <link name="{link}"/>\n'
    base = args.base_from_imu
    urdf += joint(f"base_link_to_{args.imu_frame}", "base_link", args.imu_frame, base[:3], base[3:])
    for camera, pose in zip(cameras, calibration["T_imu_cam"]):
        rpy = rpy_from_quaternion(pose["qx"], pose["qy"], pose["qz"], pose["qw"])
        urdf += joint(f"{args.imu_frame}_to_{camera}", args.imu_frame, camera,
                      (pose["px"], pose["py"], pose["pz"]), rpy)
    urdf += "</robot>\n"
    print(urdf, end="")


if __name__ == "__main__":
    main()
